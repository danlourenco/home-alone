"""hifi_french_doors: the glazed French door pairs (user, Oct 16: "i'm tired of looking at the box of them in the dining room").

Data: spec/dressing/french_doors.json (which openings, which room the leaves stand in, how far open) on the openings as built in
spec/geometry.json (ground). Look: Marina Part 1 1124/1132/1136/1142/1150 s (white leaves, 2 x 5 lites, brass knob on the
meeting stile, three hinges), film 12138 (leaves standing open on the living side). Each leaf: stiles and rails with a 3 mm
bevel, the glass between muntins on both faces, brass knob and rosette on both faces, hinges. Open pairs: a jamb lining in the
opening (the cased opening's casing is generated by SpecGreybox from the cut). The sunroom pair is mounted on the wall face with
a frame and white sheers behind the glass (the sunroom is a closed space).

Every face via hifi_lib Part.face/box; bevels as a Blender modifier on the paint (2 segments, 3 mm, angle-limited) and weighted
normals (artist-pipeline). Material names: FD_Paint, FD_Glass, FD_Brass, FD_Sheer.

  /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup -P tools/house/hifi_french_doors.py
  -> unity/HomeAlone/Assets/Models/Foyer/FrenchDoors.glb (spec metres, ground floor at y 0)
"""
import json
import math
import sys
from pathlib import Path

import bpy

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hifi_lib import Part, material   # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "unity/HomeAlone/Assets/Models/Foyer/FrenchDoors.glb"
D = json.loads((ROOT / "spec/dressing/french_doors.json").read_text())
GEO = json.loads((ROOT / "spec/geometry.json").read_text())["ground"]
L = D["leaf"]
ST, TR, BR, MU, NC, NR, T = L["stile"], L["top_rail"], L["bottom_rail"], L["muntin"], L["cols"], L["rows"], L["t"]
JT, GAP, FG, HEAD = L["jamb_t"], L["gap"], L["floor_gap"], L["head"]
WALL_HALF = 0.07

paint, glass, brass, sheer = Part("Paint", "FD_Paint"), Part("Glass", "FD_Glass"), Part("Brass", "FD_Brass"), Part("Sheer", "FD_Sheer")


def obox(p, o, e, n, a0, a1, d0, d1, y0, y1):
    """A box in a horizontal orthonormal frame: o (x, z), e and n unit (x, z) vectors; a along e, d along n, y up."""
    def pt(a, d, y): return (o[0] + a * e[0] + d * n[0], y, o[1] + a * e[1] + d * n[1])
    for y, s in ((y1, 1), (y0, -1)):
        p.face([pt(a0, d0, y), pt(a1, d0, y), pt(a1, d1, y), pt(a0, d1, y)], (0, s, 0))
    p.face([pt(a0, d1, y0), pt(a1, d1, y0), pt(a1, d1, y1), pt(a0, d1, y1)], (n[0], 0, n[1]))
    p.face([pt(a0, d0, y0), pt(a1, d0, y0), pt(a1, d0, y1), pt(a0, d0, y1)], (-n[0], 0, -n[1]))
    p.face([pt(a1, d0, y0), pt(a1, d1, y0), pt(a1, d1, y1), pt(a1, d0, y1)], (e[0], 0, e[1]))
    p.face([pt(a0, d0, y0), pt(a0, d1, y0), pt(a0, d1, y1), pt(a0, d0, y1)], (-e[0], 0, -e[1]))


def knob(p, o, e, n, a, y, d_face, outward, n_seg=16):
    """A round brass knob on a rose, turned about the leaf's thickness axis, standing out of the face at d_face toward 'outward'
    (+1: +n, -1: -n). Profile (out, radius)."""
    prof = [(0.0, 0.028), (0.008, 0.028), (0.010, 0.010), (0.045, 0.010), (0.050, 0.024), (0.060, 0.027), (0.072, 0.022), (0.076, 0.010)]
    up = (0, 1, 0)
    def P(t, r, k):
        ang = 2 * math.pi * k / n_seg; ca, sa = math.cos(ang), math.sin(ang); d = d_face + outward * t
        return (o[0] + (a + r * ca) * e[0] + d * n[0], y + r * sa, o[1] + (a + r * ca) * e[1] + d * n[1])
    rings = [[P(t, r, k) for k in range(n_seg)] for t, r in prof]
    cen = lambda t: (o[0] + a * e[0] + (d_face + outward * t) * n[0], y, o[1] + a * e[1] + (d_face + outward * t) * n[1])
    for (t0, _), (t1, _), r0, r1 in zip(prof, prof[1:], rings, rings[1:]):
        c = cen((t0 + t1) / 2)
        for k in range(n_seg):
            k2 = (k + 1) % n_seg; q = [r0[k], r0[k2], r1[k2], r1[k]]; m = [sum(v[i] for v in q) / 4 for i in range(3)]
            p.face(q, (m[0] - c[0], m[1] - c[1], m[2] - c[2]))
    ax = (n[0] * outward, 0, n[1] * outward)
    p.face(rings[0], (-ax[0], 0, -ax[2])); p.face(rings[-1], ax)


def leaf(H, u, w, width, d0, y0, y1, hinge_left):
    """One leaf: frame (H hinge point (x, z), u along the leaf from the hinge, w through its thickness), s in [0, width]."""
    d1 = d0 + T; dm = (d0 + d1) / 2
    obox(paint, H, u, w, 0, ST, d0, d1, y0, y1); obox(paint, H, u, w, width - ST, width, d0, d1, y0, y1)
    obox(paint, H, u, w, ST, width - ST, d0, d1, y1 - TR, y1); obox(paint, H, u, w, ST, width - ST, d0, d1, y0, y0 + BR)
    g0, g1, gy0, gy1 = ST, width - ST, y0 + BR, y1 - TR
    obox(glass, H, u, w, g0, g1, dm - 0.002, dm + 0.002, gy0, gy1)
    cw, rh = (g1 - g0) / NC, (gy1 - gy0) / NR
    for side in ((d0 + 0.004, dm - 0.002), (dm + 0.002, d1 - 0.004)):           # muntins on both faces of the glass, 4 mm in
        for k in range(1, NC):
            s = g0 + k * cw; obox(paint, H, u, w, s - MU / 2, s + MU / 2, *side, gy0, gy1)
        for j in range(1, NR):
            y = gy0 + j * rh
            for k in range(NC):
                sa = g0 + k * cw + (MU / 2 if k else 0); sb = g0 + (k + 1) * cw - (MU / 2 if k < NC - 1 else 0)
                obox(paint, H, u, w, sa, sb, *side, y - MU / 2, y + MU / 2)
    for yc in (y0 + 0.28, (y0 + y1) / 2 + 0.05, y1 - 0.28):                     # three hinge knuckles on the hinge edge, on the face
        obox(brass, H, u, w, -0.002, 0.016, d1, d1 + 0.012, yc - 0.045, yc + 0.045)   # away from the jamb, 12 mm proud
    for face, out in ((d0, -1), (d1, 1)):                                           # knob and rose on both faces
        knob(brass, H, u, w, width - ST / 2, L["knob_h"], face, out)


def rot(sgn, th):
    """(u', w') in the (a, r) plane for a leaf hinged on side sgn (+1: low end), opened th rad into the room (r > 0)."""
    c, s = math.cos(th), math.sin(th)
    return (sgn * c, s), ((sgn * s, -c) if sgn > 0 else (-s, -c))


def centroid(name):
    p = next(r["poly"] for r in GEO["rooms"] if r["name"] == name)
    return sum(v[0] for v in p) / len(p), sum(v[1] for v in p) / len(p)


for pr in D["pairs"]:
    o = next(o for o in GEO["openings"] if sorted(o["between"]) == sorted(pr["between"]))
    assert 0 <= pr["open_deg"] <= 180, "open_deg: 0 closed .. 180 folded flat back into the room (SpecGreybox.FrenchDoors colliders follow any angle)"
    alongX = o["axis"] == "z"                       # the wall is z = c, the opening runs along x
    c, lo, hi = o["c"], o["lo"], o["hi"]
    rc = centroid(pr["room"]); ns = 1.0 if ((rc[1] if alongX else rc[0]) > c) else -1.0
    face = c + ns * WALL_HALF
    def W(a, r):     # (along, into-room) -> spec (x, z)
        return (a, face + ns * r) if alongX else (face + ns * r, a)
    def V(va, vr):   # direction
        return (va, ns * vr) if alongX else (ns * vr, va)
    surface = pr.get("surface", False)
    th = math.radians(pr["open_deg"])
    width = (hi - lo - 2 * JT - 3 * GAP) / 2
    y0, y1 = FG, HEAD - JT - GAP
    d0 = -0.047 if surface else 0.006
    for sgn, h in ((1, lo + JT + GAP), (-1, hi - JT - GAP)):
        u, w = rot(sgn, th)
        leaf(W(h, 0), V(*u), V(*w), width, d0, y0, y1, sgn > 0)
    E, N = V(1, 0), V(0, -1)                         # along the opening; into the wall
    O = W(0, 0)
    if surface:     # a frame on the wall face round the pair, sheers 2 cm behind the glass
        for a0, a1 in ((lo, lo + JT), (hi - JT, hi)):
            obox(paint, O, E, N, a0, a1, -0.05, 0.0, 0.0, HEAD)
        obox(paint, O, E, N, lo + JT, hi - JT, -0.05, 0.0, HEAD - JT, HEAD)
        for a0, a1 in ((lo - 0.07, lo), (hi, hi + 0.07)):
            obox(paint, O, E, N, a0, a1, -0.02, 0.0, 0.0, HEAD + 0.07)
        obox(paint, O, E, N, lo - 0.07, hi + 0.07, -0.02, 0.0, HEAD, HEAD + 0.07)
        obox(sheer, O, E, N, lo + JT, hi - JT, -0.010, -0.008, FG, HEAD - JT)
    else:           # jamb linings in the opening, room face to the far face
        for a0, a1 in ((lo, lo + JT), (hi - JT, hi)):
            obox(paint, O, E, N, a0, a1, 0.003, 2 * WALL_HALF - 0.003, 0.0, HEAD)
        obox(paint, O, E, N, lo + JT, hi - JT, 0.003, 2 * WALL_HALF - 0.003, HEAD - JT, HEAD)

bpy.ops.wm.read_factory_settings(use_empty=True)
M = {"FD_Paint": material("FD_Paint", (0.88, 0.87, 0.83), 0.35), "FD_Glass": material("FD_Glass", (0.1, 0.12, 0.13), 0.05),
     "FD_Brass": material("FD_Brass", (0.75, 0.56, 0.25), 0.3), "FD_Sheer": material("FD_Sheer", (0.93, 0.92, 0.88), 0.9)}
coll = bpy.context.scene.collection
root = bpy.data.objects.new("FrenchDoors_HiFi", None); coll.objects.link(root)
for p in (paint, glass, brass, sheer):
    if not p.f: continue
    ob = p.build(coll, M); ob.parent = root
    if p is paint:   # artist-pipeline: bevelled joinery edges and weighted normals (applied on export)
        b = ob.modifiers.new("Bevel", "BEVEL"); b.width = 0.003; b.segments = 2; b.limit_method = "ANGLE"; b.angle_limit = math.radians(40)
        ob.modifiers.new("WeightedNormal", "WEIGHTED_NORMAL").keep_sharp = True
OUT.parent.mkdir(parents=True, exist_ok=True)
bpy.ops.export_scene.gltf(filepath=str(OUT), export_format="GLB", export_yup=True, export_apply=True)
print("wrote", OUT, {p.name: len(p.f) for p in (paint, glass, brass, sheer)})
